import assert from 'node:assert/strict';
import { runBrowser } from './harness.mjs';

const [scenario, target] = process.argv.slice(2);
await runBrowser(scenario, target, async ({page, cell, idle, requests, failNextAjax}) => {
  await page.goto(`${target}?season=20262027`);
  await idle();
  async function metric(table, label, value) {
    await page.waitForFunction(({table, label, value}) => {
      const row = [...document.querySelectorAll(`#${table} tbody tr`)]
        .find(row => row.querySelector('th')?.textContent.trim() === label);
      return row?.querySelector('td')?.textContent.trim() === value;
    }, {table, label, value});
  }
  if (scenario === 'favorite-recovery') {
    await page.locator('#js_switch_to_skaters_season_tot').click();
    await cell('js_skaters_total_table', 14, '2');
    await idle();
    const body = await page.locator('#js_skaters_total_table tbody').innerText();
    const removed = page.locator('#js_skaters_total_table .js-fav-del');
    const consumed = failNextAjax(url => url.pathname.endsWith('/player_favorite/'));
    await removed.press('Enter');
    await idle();
    consumed();
    await page.locator('#favorites-update-message').waitFor({state: 'visible'});
    assert.match(await page.locator('#favorites-update-message').innerText(), /Could not remove/);
    assert.equal(await page.locator('#js_skaters_total_table tbody').innerText(), body);
    assert.match(await page.locator('#js_skaters_switch').innerText(), /\(1\)/);
    assert.equal(await removed.getAttribute('aria-disabled'), 'false');
    await removed.press('Enter');
    await idle();
    await page.locator('#js_goalies_block').waitFor({state: 'visible'});
    assert.equal(await page.locator('#js_skaters_switch').isVisible(), false);
    assert.match(await page.locator('#favorites-update-message').innerText(), /successfully removed/);
    assert.equal(await page.locator('#saved-players-season').inputValue(), '20262027');
    assert.equal(requests.filter(url => url.pathname.endsWith('/player_favorite/')).length, 2);
  } else if (scenario === 'comparison-recovery') {
    const root = page.locator('#comparison-content');
    const error = page.locator('#comparison-error');
    const mode = page.locator('[data-player-type="skaters"][data-comparison-mode="season_avg"]');
    const initialBody = await page.locator('#skaters_table tbody').innerHTML();
    const modeFailure = failNextAjax(url => url.pathname.includes('/ajax_comparison_stat_switcher/'));
    await mode.click();
    await idle();
    modeFailure();
    assert.equal(await error.isVisible(), true);
    assert.equal(await root.getAttribute('data-skater-mode'), 'season_tot');
    assert.equal(await page.locator('#skaters_table tbody').innerHTML(), initialBody);
    await mode.click();
    await metric('skaters_table', 'Goals', '0.20');
    await idle();
    assert.equal(await error.isVisible(), false);
    const remove = page.locator('#skaters_table [data-comparison-remove]');
    const removeFailure = failNextAjax(url => url.pathname.includes('/player_compare/'));
    await remove.click();
    await idle();
    removeFailure();
    assert.equal(await error.isVisible(), true);
    assert.equal(await root.getAttribute('data-skaters-count'), '1');
    await metric('skaters_table', 'Goals', '0.20');
    await remove.click();
    await idle();
    assert.equal(await root.getAttribute('data-skaters-count'), '0');
    assert.equal(await error.isVisible(), false);
    await page.locator('#goalies_table').waitFor({state: 'visible'});
    const reset = page.locator('#js_goalies_block [data-comparison-reset]');
    const resetFailure = failNextAjax(url => url.pathname.includes('/reset_comparison/'));
    page.once('dialog', dialog => dialog.accept());
    await reset.click();
    await idle();
    resetFailure();
    assert.equal(await error.isVisible(), true);
    assert.equal(await root.getAttribute('data-goalies-count'), '1');
    assert.equal(await page.locator('#comparison-empty').isVisible(), false);
    page.once('dialog', dialog => dialog.accept());
    await reset.click();
    await idle();
    await page.locator('#comparison-empty').waitFor({state: 'visible'});
    assert.equal(await error.isVisible(), false);
    assert.equal(await root.getAttribute('data-skater-mode'), 'season_avg');
  } else if (scenario === 'team-recovery') {
    const defence = page.locator('#js_defencemen_sect');
    const forwards = page.locator('#js_forwards_sect');
    const error = page.locator('#team-stats-error');
    const mode = defence.locator('[data-team-stats]');
    await cell('tab2', 13, '2');
    const before = await page.locator('#tab2 tbody').innerHTML();
    const modeFailure = failNextAjax(url => url.pathname.includes('/avg/d/'));
    await mode.click();
    await idle();
    modeFailure();
    assert.equal(await error.isVisible(), true);
    assert.equal(await defence.getAttribute('data-mode'), 'tot');
    assert.equal(await page.locator('#tab2 tbody').innerHTML(), before);
    assert.equal(await mode.getAttribute('aria-disabled'), 'false');
    await mode.click();
    await idle();
    assert.equal(await error.isVisible(), false);
    assert.equal(await defence.getAttribute('data-mode'), 'avg');
    await cell('tab2', 13, '0.2');
    await defence.locator('[data-team-layout]').click();
    await idle();
    assert.equal(await defence.getAttribute('data-position'), 't');
    const joined = await page.locator('#tab2 tbody').innerHTML();
    const splitFailure = failNextAjax(url => url.pathname.includes('/avg/f/'));
    await defence.locator('[data-team-layout]').click();
    await idle();
    splitFailure();
    assert.equal(await error.isVisible(), true);
    assert.equal(await defence.getAttribute('data-position'), 't');
    assert.equal(await forwards.isVisible(), false);
    assert.equal(await page.locator('#tab2 tbody').innerHTML(), joined);
    await defence.locator('[data-team-layout]').click();
    await idle();
    assert.equal(await error.isVisible(), false);
    assert.equal(await defence.getAttribute('data-position'), 'd');
    assert.equal(await forwards.isVisible(), true);
    assert.equal(await defence.getAttribute('data-mode'), 'avg');
    assert.equal(await forwards.getAttribute('data-mode'), 'avg');
    assert.equal(await page.locator('#tab2 tbody tr').count(), 1);
    assert.equal(await page.locator('#tab3 tbody tr').count(), 2);
    await cell('tab2', 13, '0.2');
    const traded = page.locator('#tab3 tbody tr').filter({hasText: 'Traded Forward'});
    assert.equal((await traded.locator('td').nth(12).innerText()).trim(), '0.5');
  } else throw new Error(`Unknown scenario ${scenario}`);
  assert(requests.length > 0);
  const selectedRequests = requests.filter(url => !url.pathname.startsWith('/ajax_fav_players_gamelog/'));
  assert(selectedRequests.every(url => url.searchParams.get('season') === '20262027'));
});
